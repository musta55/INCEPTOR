def _export_items(lines: List[str]) -> Iterator[Tuple[str, List[str]]]:
    """The transcript as (kind, lines): "user", "agent", "think", "result" and "header"."""
    kind, body = "header", []                # type: Tuple[str, List[str]]
    for line in lines:
        if line.startswith("> ") or line == ">":
            new, first = "user", line[2:]
        elif line.startswith(("⏺ ", "● ")) or line in _EXPORT_AGENT:
            new, first = "agent", line[2:]
        elif line.startswith(_THINKING):
            new, first = "think", ""
        elif _EXPORT_RESULT.match(line):
            new, first = "result", line.split("⎿", 1)[1].strip()
        else:
            body.append(line)
            continue
        yield kind, body
        kind, body = new, [first]
    yield kind, body


def _dedent(lines: List[str]) -> str:
    """Continuation lines without the transcript's indent."""
    rest = [l for l in lines[1:] if l.strip()]
    indent = min((len(l) - len(l.lstrip(" ")) for l in rest), default=0)
    return "\n".join([lines[0]] + [l[indent:] for l in lines[1:]]).strip() if lines else ""


def _unquote(value: str) -> str:
    """A displayed ``"value"``: JSON-escaped when it parses as JSON (a regex such as
    ``"bind\\(x\\)"`` does not, and is kept as written)."""
    if len(value) < 2 or not value.startswith('"') or not value.endswith('"'):
        return value
    try:
        parsed = json.loads(value)
    except json.JSONDecodeError:
        return value[1:-1]
    return parsed if isinstance(parsed, str) else value[1:-1]


def _export_call(text: str) -> Optional[Tuple[str, Dict[str, Any]]]:
    """(tool, arguments) of an agent line that shows a call, else None."""
    head = text.split("\n", 1)[0].strip()
    if head in EXPORT_BARE:
        return EXPORT_BARE[head], {}
    match = _EXPORT_CALL.match("\n".join(l.strip() for l in text.split("\n")))
    if not match:
        return None
    display, inner = match.group(1).strip(), match.group(2).strip()
    mcp = re.match(r"^(.+?) - (.+?) \(MCP\)$", display)
    if mcp:
        return f"mcp__{mcp.group(1).strip()}__{mcp.group(2).strip()}", {"input": inner}
    if display not in EXPORT_TOOLS:
        return None
    tool, key = EXPORT_TOOLS[display]
    args: Dict[str, Any] = {}
    if tool in ("Grep", "Glob", "LS", "WebSearch", "WebFetch") and \
            re.match(r'^\w+: ', inner):
        for name, value in _KEY_VALUES.findall(inner):
            args[name] = _unquote(value.strip())
    if not args:
        args[key] = inner
    if tool == "Grep" and set(args) <= {"pattern"} and re.search(r"[*?]", args.get("pattern", "")):
        tool = "Glob"
    if display == "Explore":
        args["subagent_type"] = "Explore"
    return tool, args


def parse_export(text: str, *, source_file: str = "") -> dict:
    lines = text.split("\n")
    build = _Builder()
    version = cwd = ""
    last: Optional[Tuple[dict, str, str, Dict[str, Any]]] = None    # step, id, tool, args
    for kind, body in _export_items(lines):
        if kind == "header":
            for line in body:
                found = re.search(r"Claude Code v(\S+)", line)
                version = found.group(1) if found else version
                found = re.search(r"(?:cwd: |\s)((?:/|~/)\S[^│]*?)\s*│?\s*$", line)
                cwd = found.group(1).strip() if found and not cwd else cwd
            continue
        body = [l for l in body if not _DECOR.match(l) or not l.strip()]
        content = _dedent(body)
        if kind == "user":
            last = None
            build.user(content)
        elif kind == "think":
            build.thinking(content)
        elif kind == "result":
            if last is None:
                if build.steps and build.steps[-1]["source"] == "user":
                    build.steps[-1]["message"] += "\n" + content
                continue
            step, call_id, tool, args = last
            if tool in ("Edit", "Write"):
                found = re.match(r"^(?:Updated|Wrote \d+ lines to) (\S.*?)(?: with \d+|\n|$)", content)
                if found and not args.get("file_path"):
                    args["file_path"] = found.group(1).strip()
            build.result(step, call_id, content, content.startswith("Error"))
            last = None
        else:
            call = _export_call(content)
            collapsed = _COLLAPSED.findall(content) if call is None and \
                re.search(r"\(ctrl\+\w to expand\)", content) else []
            if call:
                step, call_id = build.call(call[0], call[1])
                last = (step, call_id, call[0], call[1])
            elif collapsed:
                for verb, count, _what in collapsed:
                    for _ in range(int(count)):
                        build.call(COLLAPSED_TOOLS[verb.lower()], {})
                build.answered = True
                last = None
            else:
                build.text(content)
                last = None
    steps = build.finish()
    gaps = ["rendered_transcript", "no_timestamps", "no_token_counts", "no_model_name",
            "no_system_prompt", "no_tool_call_ids", "no_response_grouping",
            "shortened_tool_results"]
    return schema.envelope(
        session_id=None, agent_name="claude-code", agent_version=version, model_name="",
        steps=steps, final_metrics={"total_steps": len(steps)},
        extra={"source_format": EXPORT_FORMAT, "source_file": source_file,
               "parser_version": schema.PARSER_VERSION, "agent": "claude", "cwd": cwd,
               "known_gaps": gaps})


def parse(path: Path, **kwargs: Any) -> dict:
    """Parse a transcript of either kind (``detect`` decides which)."""
    path = Path(path)
    text = path.read_text(encoding="utf-8", errors="replace")
    fmt = detect_text(text[:PROBE_BYTES])
    reader = parse_export if fmt == EXPORT_FORMAT else parse_specstory
    trajectory = reader(text, source_file=path.name)
    if kwargs.get("extra"):
        trajectory["extra"].update(kwargs["extra"])
    return trajectory
