# SpecStory

_SESSION = re.compile(r"^<!-- (.+?) Session (\S+)(?: \((.*?)\))? -->\s*$")
_VERSION = re.compile(r"^<!-- Generated by SpecStory(?:, Markdown v(\S+))? -->")
_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})\s*([^`\s]*)")
_EXT_CALL = re.compile(r"^\[external_agent_tool_call: (.+)\]\s*$")
_EXT_RESULT = re.compile(r"^\[external_agent_tool_result(?:: (\w+))?\]\s*$")
_TOOL_USE = re.compile(r'^<tool-use\b(?=[^>]*data-tool-name="([^"]*)")(?:[^>]*data-tool-type="([^"]*)")?')
_INLINE = re.compile(r"^\s*(`+)\s?(.+?)\s?\1\s*$")
_INPUT_ITEM = re.compile(r"^- (\w+): `(.*)`\s*$")


class _Fences:
    """Tracks fenced code (```` ``` ````, ``~~~``, any length) so markers inside it are text."""

    def __init__(self) -> None:
        self.open: Optional[str] = None

    def feed(self, line: str) -> bool:
        """Whether ``line`` is inside a fence or is one of its fence lines."""
        match = _FENCE.match(line)
        if self.open is None:
            if match:
                self.open = match.group(1)
                return True
            return False
        if match and match.group(1)[0] == self.open[0] and len(match.group(1)) >= len(self.open) \
                and not match.group(2):
            self.open = None
        return True


def _block_end(lines: List[str], start: int, closing: str) -> int:
    """The line that closes the block opened at ``start``: the first one ending in
    ``closing`` outside the block's fences (a tool's output may quote a transcript), or,
    when a fence is never closed, the first one at all."""
    fences = _Fences()
    for j in range(start, len(lines)):
        if j > start and fences.feed(lines[j]):
            continue
        if lines[j].rstrip().endswith(closing):
            return j
    return next((j for j in range(start, len(lines)) if lines[j].rstrip().endswith(closing)),
                len(lines) - 1)


def _spec_events(lines: List[str]) -> Iterator[Tuple[str, Any]]:
    """The transcript as events: ("header", (role, info)), ("text", line), ("think", lines),
    ("tool_use", (name, kind, lines)), ("call", (name, lines)), ("result", (error, lines)).
    Message text is not searched for fences: one left open in a pasted prompt would hide
    every message after it."""
    k = 0
    while k < len(lines):
        line = lines[k]
        header = _SPEC_HEADER.match(line)
        if header:
            yield "header", (header.group(1), header.group(2) or "")
            k += 1
            continue
        call, result, tool = _EXT_CALL.match(line), _EXT_RESULT.match(line), _TOOL_USE.match(line)
        if call or result:
            end = "[/external_agent_tool_call]" if call else "[/external_agent_tool_result]"
            j = k + 1
            while j < len(lines) and lines[j].rstrip() != end:
                j += 1
            yield ("call", (call.group(1).strip(), lines[k + 1:j])) if call else \
                ("result", (result.group(1) == "error", lines[k + 1:j]))
            k = j + 1
            continue
        if tool or line.startswith("<think>"):
            j = _block_end(lines, k, "</tool-use>" if tool else "</think>")
            body = lines[k:j + 1]
            yield ("tool_use", (tool.group(1), tool.group(2) or "", body)) if tool else \
                ("think", body)
            k = j + 1
            continue
        yield "text", line
        k += 1


def _strip_details(body: List[str]) -> List[str]:
    """A block's lines without its ``<tool-use>``/``<think>``, ``<details>`` and ``<summary>``
    wrappers."""
    out = list(body)
    if out:
        out[0] = re.sub(r"^<(?:tool-use|think)\b[^>]*>(?:<details>)?", "", out[0])
        out[-1] = re.sub(r"(?:</details>)?</(?:tool-use|think)>\s*$", "", out[-1])
    out = [l for l in out if l.strip() not in ("<details>", "</details>")]
    text = "\n".join(out)
    text = re.sub(r"<summary>.*?</summary>", "", text, count=1, flags=re.S)
    return text.split("\n")


def _segments(lines: List[str]) -> List[Tuple[str, str, str]]:
    """A block body as ("fence", lang, text), ("code", "", text) and ("text", "", text)."""
    segments: List[Tuple[str, str, str]] = []
    k = 0
    paragraph: List[str] = []

    def flush() -> None:
        if any(p.strip() for p in paragraph):
            segments.append(("text", "", "\n".join(paragraph).strip()))
        paragraph.clear()

    while k < len(lines):
        line = lines[k]
        fence = _FENCE.match(line)
        if fence:
            flush()
            ticks, lang = fence.group(1), fence.group(2)
            j = k + 1
            while j < len(lines):
                close = _FENCE.match(lines[j])
                if close and close.group(1)[0] == ticks[0] and len(close.group(1)) >= len(ticks) \
                        and not close.group(2):
                    break
                j += 1
            segments.append(("fence", lang.lower(), "\n".join(lines[k + 1:j])))
            k = j + 1
            continue
        inline = _INLINE.match(line)
        if inline:
            flush()
            segments.append(("code", "", inline.group(2)))
        elif not line.strip():
            flush()
        else:
            paragraph.append(line)
        k += 1
    flush()
    return segments


def _tool_use(name: str, kind: str, body: List[str]) -> Tuple[Dict[str, Any], str, bool]:
    """(arguments, result text, is_error) of a ``<tool-use>`` block."""
    segments = _segments(_strip_details(body))
    args: Dict[str, Any] = {}
    result: List[str] = []
    texts = [s[2] for s in segments if s[0] == "text"]
    if "**Input:**" in texts or "**Result:**" in texts:
        section = ""
        for seg_kind, _lang, text in segments:
            if text in ("**Input:**", "**Result:**"):
                section = text
            elif section == "**Input:**" and seg_kind == "text":
                for line in text.split("\n"):
                    item = _INPUT_ITEM.match(line.strip())
                    if item:
                        args[item.group(1)] = item.group(2)
            elif section == "**Result:**" or seg_kind == "fence":
                result.append(text)
    else:
        shell = name in taxonomy.SHELL_TOOLS or kind == "shell"
        primary: Optional[str] = None
        content: Optional[str] = None
        for seg_kind, lang, text in segments:
            if seg_kind == "text" and primary is None and content is None:
                args.setdefault("description", text)
            elif seg_kind == "code" and primary is None:
                primary = text
            elif seg_kind == "fence" and primary is None and content is None and (
                    (shell and lang in SHELL_LANGS) or (not shell and lang != "text")):
                if shell:
                    primary = text
                else:
                    content = text
            elif seg_kind in ("fence", "code", "text"):
                result.append(text)
        if shell:
            if primary is not None:
                args["cmd" if name == "exec_command" else "command"] = primary
        else:
            if "description" in args and name not in ("Agent", "Task"):
                result.insert(0, args.pop("description"))
            if primary is not None:
                args[PRIMARY_KEY.get(name) or KIND_KEY.get(kind) or "input"] = primary
            if content is not None:
                args["input" if name == "apply_patch" else "content"] = content
    text = "\n".join(result).strip()
    if kind == "write" or PRIMARY_KEY.get(name) == "file_path":
        _path_from_result(args, text)
    return args, text, "<tool_use_error>" in text


def _external_args(lines: List[str]) -> Dict[str, Any]:
    """The ``key: value`` input of an ``[external_agent_tool_call]`` block; ``command`` and
    ``input`` run to the end of the block."""
    values: Dict[str, List[str]] = {}
    key: Optional[str] = None
    for line in lines:
        match = re.match(r"^([a-z_]+): ?(.*)$", line)
        if match and key not in ("command", "input"):
            key = match.group(1)
            values[key] = [match.group(2)]
        elif key is not None:
            values[key].append(line)
    args: Dict[str, Any] = {}
    for key, parts in values.items():
        value = "\n".join(parts).rstrip()
        if key == "input":
            try:
                parsed = json.loads(value)
            except json.JSONDecodeError:
                parsed = None
            if isinstance(parsed, dict):
                args.update(parsed)
                continue
        args["file_path" if key == "file" else key] = value
    return args


def parse_specstory(text: str, *, source_file: str = "") -> dict:
    lines = text.split("\n")
    build = _Builder()
    label = session_id = started = version = ""
    for line in lines[:12]:
        session, generated = _SESSION.match(line), _VERSION.match(line)
        if session:
            label, session_id, started = session.group(1), session.group(2), session.group(3) or ""
        if generated:
            version = generated.group(1) or ""
    role, meta = "", {"timestamp": "", "model": ""}
    user_lines: List[str] = []
    agent_lines: List[str] = []
    markup = {"tool_use": 0, "external": 0}

    def flush_text() -> None:
        body = "\n".join(agent_lines)
        agent_lines.clear()
        body = re.sub(r"\n-{3,}\s*$", "", body.rstrip())
        build.text(body, **meta)

    def flush_user() -> None:
        body = re.sub(r"\n-{3,}\s*$", "", "\n".join(user_lines).rstrip())
        user_lines.clear()
        build.user(body, meta["timestamp"])

    for kind, value in _spec_events(lines):
        if kind == "header":
            flush_user() if role == "User" else flush_text()
            role, info = value
            stamp = _iso(info)
            model = re.sub(r"\s*\d{4}-\d{2}-\d{2}[ T][\d:]+Z?\s*$", "", info).strip()
            meta = {"timestamp": stamp, "model": "" if role == "User" else model}
            continue
        if not role:
            continue                                  # the file's title and header comments
        if role == "User":
            if kind == "text":
                user_lines.append(value)
            continue
        if kind == "text":
            agent_lines.append(value)
            continue
        flush_text()
        if kind == "think":
            body = [l for l in _strip_details(value) if l.strip()]
            build.thinking("\n".join(body), **meta)
        elif kind == "tool_use":
            name, tool_kind, body = value
            markup["tool_use"] += 1
            args, result, error = _tool_use(name, tool_kind, body)
            step, call_id = build.call(name, args, **meta)
            build.result(step, call_id, result, error)
        elif kind == "call":
            name, body = value
            markup["external"] += 1
            build.pending.append(build.call(name, _external_args(body), **meta))
        elif kind == "result":
            error, body = value
            if build.pending:
                step, call_id = build.pending.pop(0)
                build.result(step, call_id, "\n".join(body).strip(), error)
    flush_user() if role == "User" else flush_text()

    agent, agent_name = _agent(label, build.models)
    gaps = ["rendered_transcript", "no_token_counts", "no_system_prompt", "no_tool_call_ids",
            "no_response_grouping"]
    if markup["tool_use"]:
        gaps.append("partial_tool_inputs")
    if build.pending:
        gaps.append("tool_calls_without_result")
    steps = build.finish()
    return schema.envelope(
        session_id=session_id or None, agent_name=agent_name, agent_version="",
        model_name=next((m for m in build.models if m != "<synthetic>"), ""),
        steps=steps, final_metrics={"total_steps": len(steps)},
        extra={"source_format": SPECSTORY_FORMAT, "source_file": source_file,
               "parser_version": schema.PARSER_VERSION, "agent": agent,
               "session_label": label, "started": _iso(started),
               "specstory_version": version, "tool_markup": markup,
               "unanswered_tool_calls": [c for _s, c in build.pending],
               "known_gaps": gaps})


