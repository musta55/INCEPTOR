"""Markdown transcripts -> ATIF: a session saved as readable text rather than as the agent's
own log.

Two kinds are read, both recognised from their content (``detect``), never from the name:

* **SpecStory Markdown** (``.specstory/history/<time>-<title>.md``), which SpecStory writes for
  Claude Code, Codex CLI, Gemini CLI, Cursor and other agents.  A header comment names the
  agent (``<!-- Claude Code Session <id> (<time>) -->``) and each message starts with
  ``_**User (<time>)**_`` or ``_**Agent (<model> <time>)**_`` (``_**Assistant**_`` in older
  files).  A tool call is written in one of two ways:

  - ``<tool-use data-tool-type="shell" data-tool-name="Bash"><details> ... </details></tool-use>``,
    the call and its result in one block.  The block keeps only part of the input: a shell
    call's description and command, a read's path, a write's content, or an ``**Input:**``
    list (``- key: `value```); an edit keeps only its result, whose text names the file
    (``The file <path> has been updated``).
  - ``[external_agent_tool_call: Bash]`` ... ``[/external_agent_tool_call]``, the input as
    ``key: value`` lines (``command:`` runs to the end of the block, ``input:`` is JSON,
    ``file:`` is the path), and its result in a later ``[external_agent_tool_result]`` block
    (``[external_agent_tool_result: error]`` when the call failed).

* **Claude Code's** ``/export`` **transcript**, the terminal's rendering of the session:
  ``> prompt`` for the user, ``⏺ text`` for the agent, ``⏺ Bash(npm test)`` for a call
  and ``  ⎿  output`` for its (shortened) result.  The tools appear under their display names
  (``Update`` for Edit, ``Search`` for Grep and Glob, ``Fetch`` for WebFetch, ...).

A rendered transcript leaves out what a raw log records: token counts, the system prompt,
tool-call ids and which calls one response made.  Steps are therefore cut the way
``atif.claude`` cuts a dump without message ids: an agent step gathers the thinking and text
before its calls and ends when a result arrives.  Each such loss is listed in
``extra.known_gaps``.
"""
from __future__ import annotations

