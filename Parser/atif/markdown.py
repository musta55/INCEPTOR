SPECSTORY_FORMAT = "specstory_markdown"
EXPORT_FORMAT = "claude_code_export"
FORMATS = (SPECSTORY_FORMAT, EXPORT_FORMAT)
#: how much of a file ``detect`` reads
PROBE_BYTES = 1 << 16

# --------------------------------------------------------------------------- #
# the agent behind a transcript

#: SpecStory's session label (or a model name's prefix) -> (agent, ATIF agent name)
AGENTS = (("claude", "claude", "claude-code"), ("codex", "codex", "codex-cli"),
          ("gpt", "codex", "codex-cli"), ("gemini", "gemini", "gemini-cli"),
          ("qwen", "qwen", "qwen-code"), ("cursor", "cursor", "cursor"),
          ("copilot", "copilot", "github-copilot"), ("droid", "droid", "factory-droid"))


def _agent(label: str, models: List[str]) -> Tuple[str, str]:
    """(agent, ATIF agent name) from SpecStory's session label, else the models named."""
    for text in [label] + models:
        low = (text or "").lower()
        for key, agent, name in AGENTS:
            if key in low:
                return agent, name
    slug = re.sub(r"[^a-z0-9]+", "-", (label or "").lower()).strip("-")
    return (slug or "agent"), (slug or "agent")


# --------------------------------------------------------------------------- #
# detection

_SPEC_HEADER = re.compile(r"^_\*\*(User|Agent|Assistant)(?: \((.*)\))?\*\*_\s*$")
_EXPORT_AGENT = ("⏺", "●")
_EXPORT_RESULT = re.compile(r"^\s{0,4}⎿")


def detect_text(head: str) -> Optional[str]:
    """The transcript format of a file's head, or None."""
    if head.lstrip()[:1] in ("{", "["):
        return None
    lines = head.splitlines()
    if "Generated by SpecStory" in head[:2000] or (
            any(_SPEC_HEADER.match(l) for l in lines)
            and any(l.startswith(("_**Agent", "_**Assistant")) for l in lines)):
        return SPECSTORY_FORMAT
    agent_lines = sum(1 for l in lines if l.startswith(("⏺ ", "● ")))
    results = any(_EXPORT_RESULT.match(l) for l in lines)
    if any(l.startswith("⏺ ") for l in lines) or (agent_lines and results):
        if results or "Claude Code" in head:
            return EXPORT_FORMAT
    return None


def detect(path: Path) -> Optional[str]:
    try:
        with Path(path).open(encoding="utf-8", errors="replace") as handle:
            return detect_text(handle.read(PROBE_BYTES))
    except OSError:
        return None


