def calls(trajectory):
    return [(c["function_name"], c["arguments"]) for s in trajectory["steps"]
            for c in s.get("tool_calls") or []]


class DetectTests(unittest.TestCase):
    def test_each_kind_is_recognised(self):
        with tempfile.TemporaryDirectory() as tmp:
            for name, text, fmt in (("a.md", TOOL_USE, markdown.SPECSTORY_FORMAT),
                                    ("b.md", EXTERNAL, markdown.SPECSTORY_FORMAT),
                                    ("c.txt", EXPORT, markdown.EXPORT_FORMAT)):
                path = Path(tmp) / name
                path.write_text(text, encoding="utf-8")
                self.assertEqual(detect.detect(path), fmt)

    def test_other_markdown_is_not_claimed(self):
        for name in ("README.md", "Phase taxonomy.md", "ATIF-v1.7-RFC.md"):
            self.assertIsNone(detect.detect(ROOT / name), name)
        r = upload.request({"name": "notes.md", "text": "# Notes\n\n- one\n- two\n"})
        self.assertIn("Markdown transcript", r["error"])


class SpecStoryTests(unittest.TestCase):
    def test_tool_use_blocks(self):
        t = markdown.parse_specstory(TOOL_USE, source_file="s.md")
        self.assertEqual(schema.validate(t), [])
        self.assertEqual(t["agent"]["name"], "claude-code")
        self.assertEqual(t["agent"]["model_name"], "claude-opus-5-5")
        self.assertEqual(calls(t), [
            ("Bash", {"description": "Find the adapter",
                      "command": 'grep -rn "bind(items)" /runs/bug-84/app/src'}),
            ("Read", {"file_path": "/runs/bug-84/app/src/main/java/ListActivity.java"}),
            ("Edit", {"file_path": "/runs/bug-84/app/src/main/java/ListActivity.java"}),
            ("Bash", {"description": "Run the unit tests",
                      "command": "cd /runs/bug-84 && ./gradlew testDebugUnitTest"}),
            ("ToolSearch", {"max_results": "1", "query": "select:WebFetch"})])
        agent = [s for s in t["steps"] if s["source"] == "agent"]
        # thinking and text join the first call's step; a result closes each step
        self.assertEqual(agent[0]["reasoning_content"], "Find the adapter first.")
        self.assertEqual(agent[0]["message"], "I'll look for the adapter.")
        self.assertEqual(agent[0]["timestamp"], "2026-10-11T16:39:32Z")
        self.assertEqual(len(agent), 6)
        # a header quoted inside a result is the result's text, not a new message
        read = agent[1]["observation"]["results"][0]["content"]
        self.assertIn("_**User (quoted inside a result)**_", read)
        self.assertEqual([s["source"] for s in t["steps"]].count("user"), 1)
        self.assertIn("partial_tool_inputs", t["extra"]["known_gaps"])

    def test_external_agent_blocks(self):
        t = markdown.parse_specstory(EXTERNAL)
        self.assertEqual(schema.validate(t), [])
        self.assertEqual((t["agent"]["name"], t["extra"]["agent"]), ("codex-cli", "codex"))
        self.assertEqual(calls(t), [
            ("Read", {"file_path": "/runs/bug-1130/app/src/main/java/Main.java"}),
            ("Bash", {"description": "Build the app",
                      "command": "cd /runs/bug-1130 && ./gradlew assembleDebug"}),
            ("TodoWrite", {"todos": [{"content": "Fix the build", "status": "in_progress"}]})])
        # the two calls before their results are one step; results pair in order
        step = [s for s in t["steps"] if s["source"] == "agent"][0]
        self.assertEqual(len(step["tool_calls"]), 2)
        results = step["observation"]["results"]
        self.assertEqual(results[0]["content"], "1  class Main {}")
        self.assertTrue(results[1]["extra"]["is_error"])
        self.assertEqual(t["extra"]["unanswered_tool_calls"], [])

    def test_upload_labels_a_transcript(self):
        r = upload.analyze(TOOL_USE, "2026-10-11_16-39-23Z-fix.md")
        self.assertEqual((r["source"]["format"], r["source"]["agent"], r["source"]["bug"]),
                         (markdown.SPECSTORY_FORMAT, "claude", "84"))
        actions = r["trajectory"]["actions"]
        self.assertEqual([a["category"] for a in actions],
                         ["search", "read", "edit", "test", "other"])
        self.assertEqual([a["phase"] for a in actions][:4],
                         ["localization", "localization", "repair", "validation"])
        self.assertEqual(upload.analyze(EXTERNAL, "x.md")["source"]["agent"], "codex")


